namespace Netrun.Core.Plugins;

/// <summary>
/// Контракт подключаемого расширения библиотеки. Плагин — доверенный локальный код, который во
/// время composition вносит свои стратегии в реестр и затем самим ядром больше не вызывается.
/// Configure выполняется ровно один раз до первого входа, синхронно и однопоточно. Плагин не должен
/// сохранять ссылку на реестр, обращаться к сети, диску, часам или случайности и не должен удерживать
/// изменяемое разделяемое состояние: иначе нарушатся детерминизм и воспроизведение (replay) ядра.
/// </summary>
public interface INetrunPlugin
{
    /// <summary>Версия контракта ядра; несовместимое расширение отвергается до composition.</summary>
    int ApiVersion => NetrunPluginApi.Version;

    /// <summary>Стабильные метаданные плагина для диагностики; идентификатор уникален в наборе.</summary>
    PluginMetadata Metadata { get; }

    /// <summary>
    /// Регистрирует вклад плагина (например, политику стоимостей маршрутизации) в переданный реестр.
    /// Вызывается ровно один раз при создании runtime, до обработки любого входного кадра.
    /// </summary>
    /// <param name="registry">Реестр composition; действителен только на время этого вызова.</param>
    void Configure(INetrunPluginRegistry registry);
}
